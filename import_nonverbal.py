with open('static/massiveQuizData.js', 'r') as f:
    content = f.read()

json_str = content.replace('const massiveQuizData = ', '').rstrip().rstrip(';')
quizzes = json.loads(json_str)

# The topics are divided by headings like "Mirror Images (10 Questions)"
topics = re.split(r'\n(?=[A-Za-z &]+ \(\d+ Questions\))', '\n' + raw_text.strip())

for topic_block in topics:
    if not topic_block.strip(): continue
    lines = topic_block.strip().split('\n')
    topic_header = lines[0].strip()
    
    if 'Mirror Images' in topic_header: key = 'MirrorImages'
    elif 'Paper Folding' in topic_header: key = 'PaperFolding'
    elif 'Figure Series' in topic_header: key = 'FigureSeries'
    elif 'Embedded Figures' in topic_header: key = 'EmbeddedFigures'
    elif 'Cube and Dice' in topic_header: key = 'CubeDice'
    else: continue
    
    # Split blocks by \n1.\n, \n2.\n
    blocks = re.split(r'\n\d+\.\n', '\n' + '\n'.join(lines[1:]).strip())
    blocks = [b.strip() for b in blocks if b.strip()]
    
    parsed = []
    
    for block in blocks:
        block_lines = block.split('\n')
        ans_line = [l for l in block_lines if l.startswith('Answer:')]
        if not ans_line: continue
        ans_text = ans_line[0].replace('Answer:', '').strip()
        
        actual_ans = ans_text
        if ') ' in ans_text:
            actual_ans = ans_text.split(') ')[1].strip()
            
        opt_lines = [l for l in block_lines if l.startswith('a)') or l.startswith('b)') or l.startswith('c)') or l.startswith('d)')]
        opts = []
        for ol in opt_lines:
            opts.append(ol.split(')')[1].strip())
            
        q_text = "\n".join([l for l in block_lines if not l.startswith('Answer:') and not (l.startswith('a)') or l.startswith('b)') or l.startswith('c)') or l.startswith('d)'))]).strip()
        q_text = q_text.replace('\n', '<br>')
        
        opts = list(set(opts))
        while len(opts) < 4:
            opts.append(opts[0] + " variant")
        opts = opts[:4]
        if actual_ans not in opts: opts[0] = actual_ans
        
        random.shuffle(opts)
        
        parsed.append({
            "q": q_text,
            "options": opts,
            "ans": opts.index(actual_ans),
            "exp": "Solved based on visual and logical reasoning."
        })
        
    quizzes[key] = parsed
    print(f"Loaded {len(parsed)} questions into {key}")

with open('static/massiveQuizData.js', 'w') as f:
    f.write("const massiveQuizData = " + json.dumps(quizzes) + ";\n")
